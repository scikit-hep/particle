"""
This script generates the PDGID<->LHCb name mapping using the default particle table
of the LHCb software, file 'Kernel/PartProp/python/PartProp/default.ParticleTable.txt'
of the LHCb project (https://gitlab.cern.ch/lhcb/LHCb).

To refresh the mapping, update LHCB_COMMIT and LHCB_COMMIT_DATE to the latest commit
modifying that file and rerun the script from the root of the repository.
"""

from __future__ import annotations

import csv
import datetime as dt

import requests

LHCB_COMMIT = "a6c15bea75197d10eb1c3ac582036ef941105f53"
LHCB_COMMIT_DATE = "2025-05-05"
LHCB_TABLE_PATH = "Kernel/PartProp/python/PartProp/default.ParticleTable.txt"
LHCB_TABLE_URL = (
    f"https://gitlab.cern.ch/lhcb/LHCb/-/raw/{LHCB_COMMIT}/{LHCB_TABLE_PATH}"
)


def download_table(url: str = LHCB_TABLE_URL) -> list[list[str]]:
    r = requests.get(url, timeout=60)
    r.raise_for_status()

    lines = r.text.split("\n")

    return [line.split() for line in filter(lambda x: x and x[0] == " ", lines)]


def main() -> None:
    date = dt.datetime.now(tz=dt.UTC).strftime("%Y-%m-%d")
    table = download_table()
    lhcb_names = {int(pdg_id): name for name, _, pdg_id, *_ in table}

    # The mapping must be one-to-one
    if len(lhcb_names) != len(table) or len(set(lhcb_names.values())) != len(table):
        msg = "The LHCb particle table contains duplicate PDG IDs or names!"
        raise ValueError(msg)

    with open("src/particle/lhcb/data/pdgid_to_lhcbname.csv", "w") as out_csv:
        out_csv.write(
            f"# (c) Scikit-HEP project - Particle package data file - pdgid_to_lhcbname.csv - {date}\n"
        )
        out_csv.write(
            "# Auto generated by 'admin/dump_pdgid_to_lhcb.py'\n",
        )
        out_csv.write(
            f"# Source: LHCb project, {LHCB_TABLE_PATH}, commit {LHCB_COMMIT} ({LHCB_COMMIT_DATE})\n",
        )

        writer = csv.DictWriter(
            out_csv, fieldnames=("PDGID", "STR"), lineterminator="\n"
        )
        writer.writeheader()

        for pid, name in sorted(
            lhcb_names.items(), key=lambda x: (abs(int(x[0])), -int(x[0]))
        ):
            writer.writerow({"PDGID": pid, "STR": name})


if __name__ == "__main__":
    main()
